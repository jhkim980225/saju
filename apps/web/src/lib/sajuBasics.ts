/** 받침이 있으면 '이라는', 없으면 '라는' */
const ira = (word: string) => {
  const c = word.charCodeAt(word.length - 1);
  return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 > 0 ? '이라는' : '라는';
};

/** 납음 이름으로 Term 만들기 — 표에서 누를 때 */
export function napeumTerm(name: string): Term {
  const meaning = NAPEUM[name];
  return { name, short: meaning ? `'${meaning}'${ira(meaning)} 뜻의 옛 이름` : ROWS.napeum.short, body: ROWS.napeum.body };
}

/** 표 값 → 설명 찾기. 없으면 줄 설명으로 */
export function termFor(row: RowKey, value: string): Term {
  const v = value.trim();
  if (row === 'tenGods') return TEN_GODS[v] ?? ROWS.tenGods;
  if (row === 'stage') return STAGES[v] ?? ROWS.stage;
  if (row === 'shinsal') return SHINSAL[v] ?? SHINSAL[`${v}살`] ?? ROWS.shinsal;
  if (row === 'relations') return RELATIONS[v] ?? ROWS.relations;
  if (row === 'napeum') return napeumTerm(v);
  return ROWS[row];
}
