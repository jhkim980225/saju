export interface LegalDoc {
  title: string;
  body: string[];
}

type BizKey = 'NAME' | 'REPRESENTATIVE' | 'REG_NO' | 'MAIL_ORDER_NO' | 'ADDRESS' | 'EMAIL' | 'PHONE' | 'PRIVACY_OFFICER' | 'EFFECTIVE_DATE';
export type BusinessInfo = Record<BizKey, string>;

/** 지금 문서를 처음 게시한 날 — VITE_BIZ_EFFECTIVE_DATE 가 없을 때 쓴다 */
const DEFAULT_EFFECTIVE_DATE = '2026-11-25';

const env = import.meta.env as Record<string, string | undefined>;
const read = (key: BizKey): string => (env[`VITE_BIZ_${key}`] ?? '').trim();

/** apps/web/.env 에서 읽은 사업자 정보(없으면 빈 문자열) */
export const BUSINESS: BusinessInfo = {
  NAME: read('NAME'),
  REPRESENTATIVE: read('REPRESENTATIVE'),
  REG_NO: read('REG_NO'),
  MAIL_ORDER_NO: read('MAIL_ORDER_NO'),
  ADDRESS: read('ADDRESS'),
  EMAIL: read('EMAIL'),
  PHONE: read('PHONE'),
  PRIVACY_OFFICER: read('PRIVACY_OFFICER'),
  EFFECTIVE_DATE: read('EFFECTIVE_DATE') || DEFAULT_EFFECTIVE_DATE,
};

/** "상호 ○○ · 대표자 ○○ …" — 값이 있는 항목만 잇는다. 하나도 없으면 null */
export function businessLine(b: BusinessInfo = BUSINESS, keys: BizKey[] = ['NAME', 'REPRESENTATIVE', 'REG_NO', 'MAIL_ORDER_NO', 'ADDRESS', 'EMAIL', 'PHONE']): string | null {
  const label: Record<BizKey, string> = {
    NAME: '상호',
    REPRESENTATIVE: '대표자',
    REG_NO: '사업자등록번호',
    MAIL_ORDER_NO: '통신판매업 신고번호',
    ADDRESS: '주소',
    EMAIL: '이메일',
    PHONE: '전화',
    PRIVACY_OFFICER: '개인정보 보호책임자',
    EFFECTIVE_DATE: '시행일',
  };
  const parts = keys.filter((k) => b[k]).map((k) => `${label[k]} ${b[k]}`);
  return parts.length ? parts.join(' · ') : null;
}

/** 문의처 문구 — 이메일이 있으면 주소, 없으면 화면 안내 */
const contact = (b: BusinessInfo) => (b.EMAIL ? `이메일(${b.EMAIL})` : '서비스 안의 문의 안내');

