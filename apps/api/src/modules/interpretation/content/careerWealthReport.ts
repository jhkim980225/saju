import type { Element, StrengthLevel, TenGod, TenGodGroup, TwelveStage } from '@saju/core';

/** 재성·식상·비겁(과 관성·인성)의 개수로 나눈 재물 구조 */
export type MoneyStructureKey = 'siksangSaengjae' | 'jaedaSinyak' | 'bigeop' | 'gwanin' | 'hiddenWealth' | 'balanced';

export interface MoneyStructureContent {
  /** '식상생재형' */
  name: string;
  /** 한 줄 요약 — '…구조'로 끝난다 */
  title: string;
  /** 돈이 들어오고 머무는 방식 3문장 */
  flow: string;
  /** 이 구조의 강점 2문장 */
  strength: string;
  /** 살필 점 2문장 */
  watch: string;
  /** 생활 속 장면 예시 2문장 */
  example: string;
  /** 구조에 맞는 습관 1~2문장 */
  habit: string;
  /** 마무리 2문장 */
  closing: string;
}

/** 신강도별 돈 그릇 — 감당하기 좋은 크기와 일하는 방식 */
export interface StrengthWealthContent {
  vessel: string;
  scale: string;
  work: string;
  /** '이렇게 해 보세요 — …' 행동 하나 */
  action: string;
}

export type StrengthBand = 'strong' | 'mid' | 'weak';
/** 버는 방식 — 편재·정재·식신·상관 가운데 가장 두드러진 것 */
export type EarnKey = '정재' | '편재' | '식신' | '상관' | 'none';
/** 지키는 방식 — 비겁·재성·식상·인성이 몰린 곳 */
export type KeepKey = 'shared' | 'active' | 'expressive' | 'cautious' | 'steady';

/** 십성 무리별 — 일하는 방식, 분야, 대운·세운으로 들어올 때 */
export interface WorkGroupContent {
  /** 가장 강한 무리일 때 일하는 방식 3문장 */
  style: string;
  /** 잘 맞는 환경 2문장 */
  environment: string;
  /** 이 무리가 강할 때 어울리는 분야 1문장 */
  fields: string;
  /** 두 번째로 강한 무리일 때 1문장 */
  second: string;
  /** 대운 천간으로 흐를 때 2문장 */
  decade: string;
}

/** 용신 오행별 분야와 돈 습관 */
export interface ElementCareerContent {
  /** 이 기운이 힘이 되는 이유 1문장 */
  why: string;
  fields: string[];
  /** 돈 습관 2~3문장 */
  habit: string;
}

export type EmploymentKey = 'organization' | 'independent' | 'hybrid';
export interface EmploymentContent {
  title: string;
  body: string;
  tip: string;
}

