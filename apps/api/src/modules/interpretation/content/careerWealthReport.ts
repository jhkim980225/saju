import type { Element, StrengthLevel, TenGod, TenGodGroup, TwelveStage } from '@saju/core';

/** 재성·식상·비겁(과 관성·인성)의 개수로 나눈 재물 구조 */
export type MoneyStructureKey = 'siksangSaengjae' | 'jaedaSinyak' | 'bigeop' | 'gwanin' | 'hiddenWealth' | 'balanced';

export interface MoneyStructureContent {
  /** 근거용 용어 — '식상생재형' */
  term: string;
  /** 쉬운 이름(칩) — '솜씨로 버는 사람' */
  label: string;
  /** 요약 한 줄(마침표 없음) */
  title: string;
  /** 요약 장 첫 문장 — "○○님은" 뒤에 붙는다 */
  lead: string;
  /** 돈이 들어오고 머무는 방식 2~3문장 */
  flow: string;
  /** 이 구조를 쉬운 말로 풀어 주는 한 문장('사주를 보면' 뒤) */
  reason: string;
  strength: string;
  watch: string;
  example: string;
  /** 수입을 늘리는 가장 빠른 길 1문장 */
  grow: string;
  /** 돈이 새기 쉬운 순간 2문장 */
  leak: string;
  habit: string;
  closing: string;
}

/** 신강도별 돈 그릇 */
export interface StrengthWealthContent {
  /** "○○님은" 뒤에 붙는다 */
  vessel: string;
  scale: string;
  work: string;
  /** 그릇을 키우는 법 2문장 */
  grow: string;
  action: string;
}

export type StrengthBand = 'strong' | 'mid' | 'weak';
/** 버는 방식 — 편재·정재·식신·상관 가운데 가장 두드러진 것 */
export type EarnKey = '정재' | '편재' | '식신' | '상관' | 'none';
/** 지키는 방식 — 비겁·재성·식상·인성이 몰린 곳 */
export type KeepKey = 'shared' | 'active' | 'expressive' | 'cautious' | 'steady';

/** 십성 무리별 — 일하는 방식, 분야, 큰 흐름으로 들어올 때 */
export interface WorkGroupContent {
  /** 쉬운 이름 */
  name: string;
  /** 가장 강할 때 일하는 방식 3문장 — "○○님은" 뒤에 붙는다 */
  style: string;
  environment: string;
  /** 어울리는 분야 1문장 */
  fields: string;
  /** 두 번째로 강할 때 1문장 */
  second: string;
  /** 10년 흐름으로 들어올 때 2문장('…까지는' 뒤) */
  decade: string;
  /** 10년 흐름으로 들어올 때 — 돈 쪽 1문장 */
  decadeMoney: string;
  /** 가장 강할 때 — 내 몫을 이야기하는 법 1문장 */
  negotiate: string;
  /** 가장 강할 때 — 보람을 느끼는 순간 1문장 */
  praised: string;
  /** 가장 강할 때 — 기운이 빠지는 순간 1문장('반대로' 뒤) */
  tired: string;
}

/** 용신 오행별 분야와 돈 습관 */
