/**
 * 연애·결혼운 리포트 콘텐츠 — 일간별 사랑의 방식, 배우자 자리(일지), 십성 균형, 끌림, 맞는 사람, 관계 패턴,
 * 일지 합충으로 본 조율 포인트, 해마다 들어오는 인연·약속의 신호, 상황별 조언.
 *
 * 문체: 친근한 존댓말(~해요), 경향으로 말하기("~하기 쉬워요", "~한 편이에요"), 근거 → 작은 행동 순서.
 * - 성별을 정하지 않는다. 상대는 '상대', '파트너', '연인', '짝'으로 쓰고, 맞는 사람은 기질과 오행으로만 그린다.
 * - 재성과 관성을 모두 '인연의 별'로 읽는다(전통 명리의 성별 배우자성 구분을 쓰지 않음).
 * - 결혼·동거를 모두의 목표로 전제하지 않고("결혼이나 함께 사는 약속을 생각한다면"), 출산을 언급하지 않는다.
 * - 이혼·이별 단정, 공포 조장, 최상급 표현을 쓰지 않는다. 충·형·원진은 '변화와 조율의 기운'으로 설명한다.
 */
import type { Element, StrengthLevel, TenGod, TenGodGroup, TwelveStage } from '@saju/core';
import type { ScoreBand } from './types.js';

/** 일간(천간)별 사랑의 방식 — 각 1~2문장 */
export interface LoveStemContent {
  /** 다가가는 방식 */
  style: string;
  /** 마음을 표현하는 방식 */
  expression: string;
  /** 관계에서 필요한 것 */
  needs: string;
  /** 조심하면 좋은 점 + 작은 행동 */
  caution: string;
  /** 다툼이 생겼을 때의 모습 */
  conflict: string;
  /** 마무리 장의 한마디 */
  oneLine: string;
}

/** 해마다 들어오는 인연·약속의 신호 — tag: 목록 줄 꼬리표, reason: '~이/가 겹쳐' 앞에 오는 짧은 명사구, text: 풀이 1~2문장 */
export type LoveYearSignal =
  | 'combine' | 'half' | 'trine' | 'stemCombine' | 'dohwa' | 'jae' | 'gwan' | 'siksang' | 'proper' | 'steady'
  | 'clash' | 'punish' | 'wonjin' | 'harmBreak';

/** 원국에서 일지(배우자 자리)가 다른 기둥과 맺는 지지 관계 */
export type DayBranchRelation = '육합' | '반합' | '삼합' | '방합' | '충' | '형' | '자형' | '파' | '해' | '원진';

export interface LoveSituation {
  single: string;
  dating: string;
  committed: string;
}

