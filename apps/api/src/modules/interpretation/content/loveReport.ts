/**
 * 연애·결혼운 리포트 콘텐츠 — 사주를 처음 접하는 성인이 읽는 글(docs/PLAIN_KOREAN.md).
 *
 * - 정식 명리학 용어(일간·일지·재성·관성·도화·대운…)를 쓰되, 처음 나올 때의 뜻은 생성기가 termTracker 로 붙인다.
 *   한자·간지·점수는 basis('사주로 보면')에 둔다.
 * - 친근하지만 차분한 설명체. '~해요'를 기본으로, 정의·안내 문장은 '~입니다/~합니다'. 해석은 '~로 봐요/~기 쉬워요'.
 * - 성별을 정하지 않는다. 상대는 '상대', '연인', '가까운 사람'으로 쓰고, 맞는 사람은 기질로만 그린다.
 * - 전통 명리는 성별에 따라 재성 또는 관성을 배우자를 뜻하는 글자로 보지만, 이 리포트는 둘 다 인연의 기운으로 함께 읽는다(본문에서 밝힌다).
 * - 결혼·동거를 모두의 목표로 전제하지 않고, 출산을 언급하지 않는다. 연애·결혼을 하지 않는 선택도 존중한다.
 * - 이혼·이별 단정, 공포 조장, 최상급 표현을 쓰지 않는다. 충은 이별이, 도화는 바람기가 아니다.
 */
import type { Element, StrengthLevel, TenGod, TenGodGroup, TwelveStage } from '@saju/core';

/** 일간(천간)별 사랑의 방식 */
export interface LoveStemContent {
  /** 요약 장 첫 문장 — "○○님은" 뒤에 붙는다 */
  lead: string;
  /** 요약 장 칩 — 짧은 명사구 */
  chip: string;
  /** '사랑할 때의 나' 장의 한 줄 요약(마침표 없음) */
  headline: string;
  /** 다가가는 방식 2문장 — "일간이 ○○인 ○○님은" 뒤에 붙는다 */
  style: string;
  /** 마음을 표현하는 방식 2문장 */
  expression: string;
  /** 관계에서 필요한 것 2문장 */
  needs: string;
  /** 생활 속 장면 1문장 */
  scene: string;
  /** 다툼이 생겼을 때 2문장 */
  conflict: string;
  /** 조심하면 좋은 점 — [알아차릴 점, 작은 행동] */
  caution: [string, string];
  /** 이런 사람·순간에 마음이 움직여요 2문장 */
  attracted: string;
  /** 데이트할 때의 나 2문장 */
  dateStyle: string;
  /** 사랑하며 배워 가는 것 2문장 */
  growth: string;
  /** 가까운 사람이 알아 두면 좋은 나 2문장 */
  partnerNote: string;
  /** 연애할 때 자주 듣는 말 2문장 */
  heard: string;
  /** 사랑받는다고 느끼는 순간 — '상대가 … 때예요'의 가운데(관형형) */
  loveLanguage: string;
  /** 마무리 장의 한마디 */
  oneLine: string;
}

/** 해마다 들어오는 인연·약속의 신호 */
export type LoveYearSignal =
  | 'combine' | 'half' | 'trine' | 'stemCombine' | 'dohwa' | 'jae' | 'gwan' | 'siksang' | 'proper' | 'steady'
  | 'clash' | 'punish' | 'wonjin' | 'harmBreak';

/** 원국에서 일지(배우자 자리)가 다른 기둥과 맺는 지지 관계 */
export type DayBranchRelation = '육합' | '반합' | '삼합' | '방합' | '충' | '형' | '자형' | '파' | '해' | '원진';

export interface LoveSituation {
  single: string;
  dating: string;
  committed: string;
  /** 연애·결혼보다 혼자의 삶이 편한 분 */
  solo: string;
}

export interface LoveSignalContent {
  /** 10년 목록 줄 꼬리 — '…해'로 끝나는 짧은 구 */
  line: string;
  /** 이유를 이어 쓸 때 — '…고' */
  and: string;
  /** 이유의 마지막 — '…요' */
  end: string;
  /** 가까운 3년 풀이 1~2문장 */
  text: string;
}

