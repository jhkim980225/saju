/** 화면에서 부를 이름 — 비었거나 "나"·"본인"이면 이름 없이 쓴다 */
export function displayName(name: string | null | undefined): string | null {
  const n = (name ?? '').trim();
  return n && n !== '나' && n !== '본인' ? n : null;
}

/** 이름 + 조사. 이름이 없으면 빈 문자열(주어를 빼도 자연스러운 한국어) */
export function nameSubject(name: string | null, particle: '은' | '이' | '에게' | '의' | '도'): string {
  return name ? `${name}님${particle} ` : '';
}

/**
 * 일간 문구의 "갑목은 / 갑목의 / 갑목에게 / 을목 특유의" 를 이름으로 바꾼다. 이름이 없으면 주어를 뺀다.
 * stemShort 는 '갑목' 처럼 한자 앞 두 글자.
 */
export function personalize(text: string, stemShort: string, name: string | null): string {
  const map: Record<string, '은' | '이' | '에게' | '의'> = { 은: '은', 는: '은', 이: '이', 가: '이', 에게: '에게', 의: '의' };
  return text
    .replace(new RegExp(`${stemShort}(에게|은|는|이|가|의) `, 'g'), (_, p: string) => nameSubject(name, map[p]!))
    .replace(new RegExp(`${stemShort} `, 'g'), name ? `${name}님 ` : '');
}
