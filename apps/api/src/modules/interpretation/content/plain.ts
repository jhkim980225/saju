const EL_WORD: Record<string, string> = { 목: '나무', 화: '불', 토: '흙', 금: '쇠', 수: '물' };
const EL_SUBJECT: Record<string, string> = { 목: '나무가', 화: '불이', 토: '흙이', 금: '쇠가', 수: '물이' };

/** 오행 설명 문구의 '목이 / 화(火)의 / 토(土)의' 같은 말을 쉬운 이름으로 */
export function plainElementText(text: string): string {
  return text
    .replace(/^(목|화|토|금|수)(이|가) /, (_, el: string) => `${EL_SUBJECT[el]} `)
    .replace(/(목|화|토|금|수)\((木|火|土|金|水)\)/g, (_, el: string) => EL_WORD[el]!)
    .replace(/(^|[\s,])(목|화|토|금|수)의 /g, (_, pre: string, el: string) => `${pre}${EL_WORD[el]}의 `);
}

